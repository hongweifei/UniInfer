//! Greedy text generation over an abstract tokenizer.

use std::sync::Arc;
use std::time::Instant;

use uniinfer_core::{
    CancelToken, EngineError, EngineSession, Result, Tensor, TensorData, TensorDtype, TensorSpec,
};

use crate::sampling::{Rng, Sampling, clock_seed, sample};
use crate::tokenizer::Tokenizer;

/// Why generation stopped.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FinishReason {
    /// The model emitted its EOS token.
    Eos,
    /// The caller's byte sink rejected further output.
    SinkClosed,
    /// `max_tokens` was reached.
    Length,
}

/// One generation request's decoding limits and deadline.
#[derive(Debug, Clone, Copy)]
pub struct GenerationSpec {
    pub max_tokens: usize,
    pub sampling: Sampling,
    pub deadline: Option<Instant>,
}

impl GenerationSpec {
    #[must_use]
    pub fn greedy(max_tokens: usize) -> Self {
        Self {
            max_tokens,
            sampling: Sampling::greedy(),
            deadline: None,
        }
    }
}

/// Generated bytes plus accounting for the tokens consumed to produce them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GenerationOutput {
    pub bytes: Vec<u8>,
    pub tokens: usize,
    pub finish: FinishReason,
}

/// Autoregressive text generator bound to one tokenizer and context size.
pub struct TextGenerator {
    tokenizer: Arc<dyn Tokenizer>,
    vocab_size: usize,
    context_len: usize,
    eos_token: Option<u32>,
}

impl TextGenerator {
    #[must_use]
    pub fn new(
        tokenizer: Arc<dyn Tokenizer>,
        vocab_size: usize,
        context_len: usize,
        eos_token: Option<u32>,
    ) -> Self {
        Self {
            tokenizer,
            vocab_size,
            context_len,
            eos_token,
        }
    }

    #[must_use]
    pub fn tokenizer(&self) -> &dyn Tokenizer {
        self.tokenizer.as_ref()
    }

    /// Count prompt tokens exactly as `generate` will encode them.
    pub fn count_tokens(&self, prompt: &str) -> Result<usize> {
        let prompt = if prompt.is_empty() { " " } else { prompt };
        Ok(self.tokenizer.encode(prompt)?.len())
    }

    /// Generate tokens until `max_tokens`, EOS, sink rejection or cancellation.
    pub fn generate(
        &self,
        session: &dyn EngineSession,
        prompt: &str,
        max_tokens: usize,
        cancel: &CancelToken,
        on_bytes: &mut dyn FnMut(&[u8]) -> bool,
    ) -> Result<GenerationOutput> {
        self.generate_with(
            session,
            prompt,
            cancel,
            GenerationSpec::greedy(max_tokens),
            on_bytes,
        )
    }

    /// Generate with explicit sampling controls.
    pub fn generate_with(
        &self,
        session: &dyn EngineSession,
        prompt: &str,
        cancel: &CancelToken,
        spec: GenerationSpec,
        on_bytes: &mut dyn FnMut(&[u8]) -> bool,
    ) -> Result<GenerationOutput> {
        self.generate_with_augmented(session, prompt, &[], cancel, spec, on_bytes)
    }

    /// Generate from a prompt plus zero or more images.
    pub fn generate_with_images(
        &self,
        session: &dyn EngineSession,
        prompt: &str,
        images: &[Vec<u8>],
        cancel: &CancelToken,
        spec: GenerationSpec,
        on_bytes: &mut dyn FnMut(&[u8]) -> bool,
    ) -> Result<GenerationOutput> {
        let extra = if images.is_empty() {
            Vec::new()
        } else {
            let encoded = uniinfer_core::ImageBatch::encode(images)?;
            vec![Tensor::new(
                "image",
                vec![encoded.len()],
                TensorData::U8(encoded),
            )?]
        };
        self.generate_with_augmented(session, prompt, &extra, cancel, spec, on_bytes)
    }

    /// Generate with arbitrary auxiliary tensors sent on every forward pass.
    pub fn generate_with_augmented(
        &self,
        session: &dyn EngineSession,
        prompt: &str,
        extra: &[Tensor],
        cancel: &CancelToken,
        spec: GenerationSpec,
        on_bytes: &mut dyn FnMut(&[u8]) -> bool,
    ) -> Result<GenerationOutput> {
        for tensor in extra {
            if !session.inputs().iter().any(|spec| spec.name == tensor.name) {
                return Err(EngineError::Other(format!(
                    "session has no auxiliary input {}",
                    tensor.name
                )));
            }
        }
        let GenerationSpec {
            max_tokens,
            sampling,
            deadline,
        } = spec;
        sampling.validate()?;
        if deadline.is_some_and(|deadline| Instant::now() >= deadline) {
            return Err(EngineError::Timeout);
        }
        if cancel.is_cancelled() {
            return Err(EngineError::Cancelled);
        }
        if max_tokens == 0 {
            return Ok(GenerationOutput {
                bytes: Vec::new(),
                tokens: 0,
                finish: FinishReason::Length,
            });
        }

        let prompt = if prompt.is_empty() { " " } else { prompt };
        let mut ids: Vec<i64> = self
            .tokenizer
            .encode(prompt)?
            .into_iter()
            .map(i64::from)
            .collect();

        let required = ids.len() + max_tokens;
        if required > self.context_len {
            return Err(EngineError::InputTooLong {
                input: required,
                limit: self.context_len,
            });
        }

        let id_spec = find_input(session, "input_ids")
            .or_else(|| find_i64_input(session))
            .ok_or_else(|| EngineError::Other("model has no int64 input_ids".into()))?;
        let mask_spec = find_input(session, "attention_mask");
        let logits_spec = find_logits(session)
            .ok_or_else(|| EngineError::Other("model has no float logits output".into()))?;
        let mut generated = Vec::with_capacity(max_tokens);
        let mut generated_tokens = Vec::with_capacity(max_tokens);
        let mut tokens = 0usize;
        let mut finish = FinishReason::Length;
        let mut rng = Rng::new(sampling.seed.unwrap_or_else(clock_seed));
        for _ in 0..max_tokens {
            if deadline.is_some_and(|deadline| Instant::now() >= deadline) {
                return Err(EngineError::Timeout);
            }
            if cancel.is_cancelled() {
                return Err(EngineError::Cancelled);
            }

            let length = ids.len();
            let mut tensors = vec![Tensor::new(
                id_spec.name.clone(),
                vec![1, length],
                TensorData::I64(ids.clone()),
            )?];
            if let Some(mask) = &mask_spec {
                tensors.push(Tensor::new(
                    mask.name.clone(),
                    vec![1, length],
                    TensorData::I64(vec![1; length]),
                )?);
            }
            tensors.extend(extra.iter().cloned());

            let outputs = session.run_with_deadline(tensors, deadline)?;
            if deadline.is_some_and(|deadline| Instant::now() >= deadline) {
                return Err(EngineError::Timeout);
            }
            if cancel.is_cancelled() {
                return Err(EngineError::Cancelled);
            }

            let logits = outputs
                .iter()
                .find(|tensor| tensor.name == logits_spec.name)
                .ok_or_else(|| {
                    EngineError::Other(format!("missing output {}", logits_spec.name))
                })?;
            let row = last_row(logits, self.vocab_size, self.tokenizer.vocab_size())?;
            let next = sample(row, &sampling, &mut rng, &generated_tokens)?;
            if self.eos_token == Some(next) {
                finish = FinishReason::Eos;
                break;
            }
            let bytes = self.tokenizer.decode(next)?;

            generated.extend_from_slice(&bytes);
            generated_tokens.push(next);
            tokens += 1;
            if !on_bytes(&bytes) {
                finish = FinishReason::SinkClosed;
                break;
            }
            ids.push(i64::from(next));
        }
        Ok(GenerationOutput {
            bytes: generated,
            tokens,
            finish,
        })
    }
}

fn find_input(session: &dyn EngineSession, name: &str) -> Option<TensorSpec> {
    session
        .inputs()
        .iter()
        .find(|spec| spec.dtype == TensorDtype::I64 && spec.name.contains(name))
        .cloned()
}

fn find_i64_input(session: &dyn EngineSession) -> Option<TensorSpec> {
    session
        .inputs()
        .iter()
        .find(|spec| spec.dtype == TensorDtype::I64)
        .cloned()
}

fn find_logits(session: &dyn EngineSession) -> Option<TensorSpec> {
    session
        .outputs()
        .iter()
        .find(|spec| spec.dtype == TensorDtype::F32 && spec.name.contains("logits"))
        .or_else(|| {
            session
                .outputs()
                .iter()
                .find(|spec| spec.dtype == TensorDtype::F32)
        })
        .cloned()
}

fn last_row(tensor: &Tensor, vocab_size: usize, tokenizer_vocab: usize) -> Result<&[f32]> {
    let values = match &tensor.data {
        TensorData::F32(values) => values,
        other => {
            return Err(EngineError::Other(format!(
                "expected f32 logits, got {:?}",
                other.dtype()
            )));
        }
    };
    let (vocab, offset) = match tensor.shape.as_slice() {
        [1, seq, vocab] if *vocab == vocab_size => (vocab_size, (*seq - 1) * vocab_size),
        [1, vocab] if *vocab == vocab_size => (vocab_size, 0),
        shape => {
            return Err(EngineError::Other(format!(
                "unexpected logits shape {shape:?}, expected [1, seq, {vocab_size}]"
            )));
        }
    };
    Ok(&values[offset..offset + vocab.min(tokenizer_vocab)])
}

#[cfg(test)]
mod tests {
    use std::sync::Mutex;

    use crate::tokenizer::ByteTokenizer;

    use super::*;

    struct Scripted {
        inputs: Vec<TensorSpec>,
        outputs: Vec<TensorSpec>,
        seen: Mutex<Vec<Vec<i64>>>,
        images: Mutex<Vec<Vec<Vec<u8>>>>,
    }

    impl Scripted {
        fn new() -> Self {
            Self {
                inputs: vec![
                    TensorSpec {
                        name: "input_ids".into(),
                        dtype: TensorDtype::I64,
                        shape: vec![Some(1), None],
                    },
                    TensorSpec {
                        name: "image".into(),
                        dtype: TensorDtype::U8,
                        shape: vec![None],
                    },
                ],
                outputs: vec![TensorSpec {
                    name: "logits".into(),
                    dtype: TensorDtype::F32,
                    shape: vec![Some(1), None, Some(256)],
                }],
                seen: Mutex::new(Vec::new()),
                images: Mutex::new(Vec::new()),
            }
        }
    }

    impl EngineSession for Scripted {
        fn inputs(&self) -> &[TensorSpec] {
            &self.inputs
        }

        fn outputs(&self) -> &[TensorSpec] {
            &self.outputs
        }

        fn run(&self, inputs: Vec<Tensor>) -> Result<Vec<Tensor>> {
            let ids = match &inputs[0].data {
                TensorData::I64(values) => values.clone(),
                _ => return Err(EngineError::Other("expected i64".into())),
            };
            let seq = ids.len();
            self.seen.lock().expect("lock").push(ids.clone());
            if let Some(image) = inputs.iter().find(|tensor| tensor.name == "image")
                && let TensorData::U8(bytes) = &image.data
            {
                let images = uniinfer_core::ImageBatch::decode(bytes)?;
                let images = images.as_slice().to_vec();
                self.images.lock().expect("lock").push(images);
            }
            let mut logits = vec![0.0f32; seq * 256];
            for position in 0..seq {
                let next = (ids[position] + 1) % 256;
                logits[position * 256 + next as usize] = 1.0;
            }
            Ok(vec![Tensor::new(
                "logits",
                vec![1, seq, 256],
                TensorData::F32(logits),
            )?])
        }

        fn cancel(&self) {}
    }

    fn generator() -> TextGenerator {
        TextGenerator::new(
            Arc::new(ByteTokenizer::new(256).expect("tokenizer")),
            256,
            64,
            None,
        )
    }

    #[test]
    fn greedy_byte_generation_advances_one_byte_per_step() {
        let session = Scripted::new();
        let mut bytes = Vec::new();
        let generated = generator()
            .generate(&session, "ab", 3, &CancelToken::new(), &mut |chunk| {
                bytes.extend_from_slice(chunk);
                true
            })
            .expect("generate");

        assert_eq!(generated.bytes, b"cde");
        assert_eq!(generated.tokens, 3);
        assert_eq!(generated.finish, FinishReason::Length);
        assert_eq!(bytes, b"cde");
        let seen = session.seen.lock().expect("lock");
        assert_eq!(seen.len(), 3);
        assert_eq!(seen[0], vec![97, 98]);
        assert_eq!(seen[2], vec![97, 98, 99, 100]);
    }

    #[test]
    fn image_is_sent_on_every_forward_pass() {
        let session = Scripted::new();
        let generated = generator()
            .generate_with_images(
                &session,
                "ab",
                &[vec![1, 2, 3]],
                &CancelToken::new(),
                GenerationSpec::greedy(2),
                &mut |_| true,
            )
            .expect("generate");
        assert_eq!(generated.bytes, b"cd");
        assert_eq!(
            *session.images.lock().expect("lock"),
            vec![vec![vec![1, 2, 3]], vec![vec![1, 2, 3]]]
        );
    }

    #[test]
    fn multiple_images_are_sent_as_one_batch() {
        let session = Scripted::new();
        let generated = generator()
            .generate_with_images(
                &session,
                "ab",
                &[vec![1, 2], vec![3, 4, 5]],
                &CancelToken::new(),
                GenerationSpec::greedy(2),
                &mut |_| true,
            )
            .expect("generate");
        assert_eq!(generated.bytes, b"cd");
        assert_eq!(
            *session.images.lock().expect("lock"),
            vec![
                vec![vec![1, 2], vec![3, 4, 5]],
                vec![vec![1, 2], vec![3, 4, 5]]
            ]
        );
    }

    #[test]
    fn context_overflow_is_rejected() {
        let session = Scripted::new();
        let generator = TextGenerator::new(
            Arc::new(ByteTokenizer::new(256).expect("tokenizer")),
            256,
            8,
            None,
        );
        let error = generator
            .generate(&session, "abcdef", 3, &CancelToken::new(), &mut |_| true)
            .expect_err("must fail");
        assert!(matches!(error, EngineError::InputTooLong { .. }));
    }

    #[test]
    fn pre_cancelled_generation_returns_cancelled() {
        let session = Scripted::new();
        let cancel = CancelToken::new();
        cancel.cancel();
        let error = generator()
            .generate(&session, "ab", 3, &cancel, &mut |_| true)
            .expect_err("must be cancelled");
        assert!(matches!(error, EngineError::Cancelled));
    }
}
