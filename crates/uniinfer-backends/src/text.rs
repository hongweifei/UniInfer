//! Greedy text generation over an abstract tokenizer.

use std::sync::Arc;

use uniinfer_core::{
    CancelToken, EngineError, EngineSession, Result, Tensor, TensorData, TensorDtype, TensorSpec,
};

use crate::tokenizer::Tokenizer;

/// Why generation stopped.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FinishReason {
    /// The model emitted its EOS token.
    Eos,
    /// The caller's byte sink rejected further output.
    SinkClosed,
    /// `max_tokens` was reached.
    Length,
}

/// Decoding controls for one generation request.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Sampling {
    /// `0` means greedy decoding; positive values divide logits.
    pub temperature: f32,
    /// Nucleus probability mass; `1.0` disables nucleus filtering.
    pub top_p: f32,
    /// Keep the best K candidates; `0` keeps every finite token.
    pub top_k: usize,
    /// Deterministic sampling seed; `None` seeds from the clock.
    pub seed: Option<u64>,
}

impl Default for Sampling {
    fn default() -> Self {
        Self {
            temperature: 0.0,
            top_p: 1.0,
            top_k: 0,
            seed: None,
        }
    }
}

impl Sampling {
    #[must_use]
    pub fn greedy() -> Self {
        Self::default()
    }

    pub fn validate(&self) -> Result<()> {
        if !self.temperature.is_finite() || !(0.0..=2.0).contains(&self.temperature) {
            return Err(EngineError::InvalidSampling(
                "temperature must be between 0 and 2".into(),
            ));
        }
        if !self.top_p.is_finite() || self.top_p <= 0.0 || self.top_p > 1.0 {
            return Err(EngineError::InvalidSampling(
                "top_p must be in (0, 1]".into(),
            ));
        }
        if self.top_k > 4096 {
            return Err(EngineError::InvalidSampling(
                "top_k must be at most 4096".into(),
            ));
        }
        Ok(())
    }
}

/// Generated bytes plus accounting for the tokens consumed to produce them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GenerationOutput {
    pub bytes: Vec<u8>,
    pub tokens: usize,
    pub finish: FinishReason,
}

/// Greedy text generator bound to one tokenizer and context size.
pub struct TextGenerator {
    tokenizer: Arc<dyn Tokenizer>,
    vocab_size: usize,
    context_len: usize,
    eos_token: Option<u32>,
}

impl TextGenerator {
    #[must_use]
    pub fn new(
        tokenizer: Arc<dyn Tokenizer>,
        vocab_size: usize,
        context_len: usize,
        eos_token: Option<u32>,
    ) -> Self {
        Self {
            tokenizer,
            vocab_size,
            context_len,
            eos_token,
        }
    }

    #[must_use]
    pub fn tokenizer(&self) -> &dyn Tokenizer {
        self.tokenizer.as_ref()
    }

    /// Count prompt tokens exactly as `generate` will encode them.
    pub fn count_tokens(&self, prompt: &str) -> Result<usize> {
        let prompt = if prompt.is_empty() { " " } else { prompt };
        Ok(self.tokenizer.encode(prompt)?.len())
    }

    /// Generate tokens until `max_tokens`, EOS, sink rejection or cancellation.
    pub fn generate(
        &self,
        session: &dyn EngineSession,
        prompt: &str,
        max_tokens: usize,
        cancel: &CancelToken,
        on_bytes: &mut dyn FnMut(&[u8]) -> bool,
    ) -> Result<GenerationOutput> {
        self.generate_with(
            session,
            prompt,
            max_tokens,
            cancel,
            &Sampling::greedy(),
            on_bytes,
        )
    }

    /// Generate with explicit sampling controls.
    pub fn generate_with(
        &self,
        session: &dyn EngineSession,
        prompt: &str,
        max_tokens: usize,
        cancel: &CancelToken,
        sampling: &Sampling,
        on_bytes: &mut dyn FnMut(&[u8]) -> bool,
    ) -> Result<GenerationOutput> {
        sampling.validate()?;
        if cancel.is_cancelled() {
            return Err(EngineError::Cancelled);
        }
        if max_tokens == 0 {
            return Ok(GenerationOutput {
                bytes: Vec::new(),
                tokens: 0,
                finish: FinishReason::Length,
            });
        }

        let prompt = if prompt.is_empty() { " " } else { prompt };
        let mut ids: Vec<i64> = self
            .tokenizer
            .encode(prompt)?
            .into_iter()
            .map(i64::from)
            .collect();

        let required = ids.len() + max_tokens;
        if required > self.context_len {
            return Err(EngineError::InputTooLong {
                input: required,
                limit: self.context_len,
            });
        }

        let id_spec = find_input(session, "input_ids")
            .or_else(|| find_i64_input(session))
            .ok_or_else(|| EngineError::Other("model has no int64 input_ids".into()))?;
        let mask_spec = find_input(session, "attention_mask");
        let logits_spec = find_logits(session)
            .ok_or_else(|| EngineError::Other("model has no float logits output".into()))?;

        let mut generated = Vec::with_capacity(max_tokens);
        let mut tokens = 0usize;
        let mut finish = FinishReason::Length;
        let mut rng = Rng::new(sampling.seed.unwrap_or_else(clock_seed));
        for _ in 0..max_tokens {
            if cancel.is_cancelled() {
                return Err(EngineError::Cancelled);
            }

            let length = ids.len();
            let mut tensors = vec![Tensor::new(
                id_spec.name.clone(),
                vec![1, length],
                TensorData::I64(ids.clone()),
            )?];
            if let Some(mask) = &mask_spec {
                tensors.push(Tensor::new(
                    mask.name.clone(),
                    vec![1, length],
                    TensorData::I64(vec![1; length]),
                )?);
            }

            let outputs = session.run(tensors)?;
            if cancel.is_cancelled() {
                return Err(EngineError::Cancelled);
            }

            let logits = outputs
                .iter()
                .find(|tensor| tensor.name == logits_spec.name)
                .ok_or_else(|| {
                    EngineError::Other(format!("missing output {}", logits_spec.name))
                })?;
            let row = last_row(logits, self.vocab_size, self.tokenizer.vocab_size())?;
            let next = sample(row, sampling, &mut rng)?;
            let bytes = self.tokenizer.decode(next)?;

            generated.extend_from_slice(&bytes);
            tokens += 1;
            if !on_bytes(&bytes) {
                finish = FinishReason::SinkClosed;
                break;
            }
            if self.eos_token == Some(next) {
                finish = FinishReason::Eos;
                break;
            }
            ids.push(i64::from(next));
        }
        Ok(GenerationOutput {
            bytes: generated,
            tokens,
            finish,
        })
    }
}

fn find_input(session: &dyn EngineSession, name: &str) -> Option<TensorSpec> {
    session
        .inputs()
        .iter()
        .find(|spec| spec.dtype == TensorDtype::I64 && spec.name.contains(name))
        .cloned()
}

fn find_i64_input(session: &dyn EngineSession) -> Option<TensorSpec> {
    session
        .inputs()
        .iter()
        .find(|spec| spec.dtype == TensorDtype::I64)
        .cloned()
}

fn find_logits(session: &dyn EngineSession) -> Option<TensorSpec> {
    session
        .outputs()
        .iter()
        .find(|spec| spec.dtype == TensorDtype::F32 && spec.name.contains("logits"))
        .or_else(|| {
            session
                .outputs()
                .iter()
                .find(|spec| spec.dtype == TensorDtype::F32)
        })
        .cloned()
}

fn last_row(tensor: &Tensor, vocab_size: usize, tokenizer_vocab: usize) -> Result<&[f32]> {
    let values = match &tensor.data {
        TensorData::F32(values) => values,
        other => {
            return Err(EngineError::Other(format!(
                "expected f32 logits, got {:?}",
                other.dtype()
            )));
        }
    };
    let (vocab, offset) = match tensor.shape.as_slice() {
        [1, seq, vocab] if *vocab == vocab_size => (vocab_size, (*seq - 1) * vocab_size),
        [1, vocab] if *vocab == vocab_size => (vocab_size, 0),
        shape => {
            return Err(EngineError::Other(format!(
                "unexpected logits shape {shape:?}, expected [1, seq, {vocab_size}]"
            )));
        }
    };
    Ok(&values[offset..offset + vocab.min(tokenizer_vocab)])
}

fn sample(row: &[f32], sampling: &Sampling, rng: &mut Rng) -> Result<u32> {
    if sampling.temperature <= 0.0 || row.is_empty() {
        let mut best = 0usize;
        let mut best_value = f32::NEG_INFINITY;
        for (index, value) in row.iter().enumerate() {
            if value.is_finite() && *value > best_value {
                best_value = *value;
                best = index;
            }
        }
        return u32::try_from(best).map_err(|_| EngineError::Other("token id overflow".into()));
    }

    let max = row
        .iter()
        .copied()
        .filter(|value| value.is_finite())
        .fold(f32::NEG_INFINITY, f32::max);
    if !max.is_finite() {
        return Err(EngineError::Other("sampling logits are not finite".into()));
    }
    let temperature = sampling.temperature;
    let mut candidates = row
        .iter()
        .enumerate()
        .filter(|(_, value)| value.is_finite())
        .map(|(index, value)| (((value - max) / temperature).exp(), index))
        .collect::<Vec<_>>();
    if sampling.top_k > 0 && candidates.len() > sampling.top_k {
        candidates.select_nth_unstable_by(sampling.top_k - 1, |a, b| b.0.total_cmp(&a.0));
        candidates.truncate(sampling.top_k);
    }
    candidates.sort_unstable_by(|a, b| b.0.total_cmp(&a.0));

    let mut total = candidates.iter().map(|(weight, _)| weight).sum::<f32>();
    if !total.is_finite() || total <= 0.0 {
        return Err(EngineError::Other("sampling weights are not finite".into()));
    }
    if sampling.top_p < 1.0 {
        let cutoff = total * sampling.top_p;
        let mut cumulative = 0.0;
        let keep = candidates
            .iter()
            .position(|(weight, _)| {
                cumulative += weight;
                cumulative >= cutoff
            })
            .map_or(candidates.len(), |index| index + 1);
        candidates.truncate(keep);
        total = candidates.iter().map(|(weight, _)| weight).sum::<f32>();
    }

    let mut target = rng.next_f32() * total;
    for (weight, index) in &candidates {
        if target < *weight {
            return u32::try_from(*index)
                .map_err(|_| EngineError::Other("token id overflow".into()));
        }
        target -= *weight;
    }
    candidates
        .last()
        .and_then(|(_, index)| u32::try_from(*index).ok())
        .ok_or_else(|| EngineError::Other("empty sampling candidates".into()))
}

struct Rng(u64);

impl Rng {
    fn new(seed: u64) -> Self {
        Self(seed.max(1))
    }

    fn next_f32(&mut self) -> f32 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        (self.0 >> 40) as f32 / (1u64 << 24) as f32
    }
}

fn clock_seed() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0x9e37_79b9_7f4a_7c15, |duration| {
            duration.as_nanos() as u64 ^ 0x9e37_79b9_7f4a_7c15
        })
}

#[cfg(test)]
mod tests {
    use std::sync::Mutex;

    use crate::tokenizer::ByteTokenizer;

    use super::*;

    struct Scripted {
        inputs: Vec<TensorSpec>,
        outputs: Vec<TensorSpec>,
        seen: Mutex<Vec<Vec<i64>>>,
    }

    impl Scripted {
        fn new() -> Self {
            Self {
                inputs: vec![TensorSpec {
                    name: "input_ids".into(),
                    dtype: TensorDtype::I64,
                    shape: vec![Some(1), None],
                }],
                outputs: vec![TensorSpec {
                    name: "logits".into(),
                    dtype: TensorDtype::F32,
                    shape: vec![Some(1), None, Some(256)],
                }],
                seen: Mutex::new(Vec::new()),
            }
        }
    }

    impl EngineSession for Scripted {
        fn inputs(&self) -> &[TensorSpec] {
            &self.inputs
        }

        fn outputs(&self) -> &[TensorSpec] {
            &self.outputs
        }

        fn run(&self, inputs: Vec<Tensor>) -> Result<Vec<Tensor>> {
            let ids = match &inputs[0].data {
                TensorData::I64(values) => values.clone(),
                _ => return Err(EngineError::Other("expected i64".into())),
            };
            let seq = ids.len();
            self.seen.lock().expect("lock").push(ids.clone());
            let mut logits = vec![0.0f32; seq * 256];
            for position in 0..seq {
                let next = (ids[position] + 1) % 256;
                logits[position * 256 + next as usize] = 1.0;
            }
            Ok(vec![Tensor::new(
                "logits",
                vec![1, seq, 256],
                TensorData::F32(logits),
            )?])
        }

        fn cancel(&self) {}
    }

    fn generator() -> TextGenerator {
        TextGenerator::new(
            Arc::new(ByteTokenizer::new(256).expect("tokenizer")),
            256,
            64,
            None,
        )
    }

    #[test]
    fn greedy_byte_generation_advances_one_byte_per_step() {
        let session = Scripted::new();
        let mut bytes = Vec::new();
        let generated = generator()
            .generate(&session, "ab", 3, &CancelToken::new(), &mut |chunk| {
                bytes.extend_from_slice(chunk);
                true
            })
            .expect("generate");

        assert_eq!(generated.bytes, b"cde");
        assert_eq!(generated.tokens, 3);
        assert_eq!(generated.finish, FinishReason::Length);
        assert_eq!(bytes, b"cde");
        let seen = session.seen.lock().expect("lock");
        assert_eq!(seen.len(), 3);
        assert_eq!(seen[0], vec![97, 98]);
        assert_eq!(seen[2], vec![97, 98, 99, 100]);
    }

    #[test]
    fn context_overflow_is_rejected() {
        let session = Scripted::new();
        let generator = TextGenerator::new(
            Arc::new(ByteTokenizer::new(256).expect("tokenizer")),
            256,
            8,
            None,
        );
        let error = generator
            .generate(&session, "abcdef", 3, &CancelToken::new(), &mut |_| true)
            .expect_err("must fail");
        assert!(matches!(error, EngineError::InputTooLong { .. }));
    }

    #[test]
    fn sampling_validation_rejects_out_of_range() {
        let mut sampling = Sampling::default();
        assert!(sampling.validate().is_ok());
        sampling.temperature = 2.1;
        assert!(matches!(
            sampling.validate(),
            Err(EngineError::InvalidSampling(_))
        ));
        sampling = Sampling {
            temperature: 1.0,
            top_p: 0.0,
            ..Sampling::default()
        };
        assert!(matches!(
            sampling.validate(),
            Err(EngineError::InvalidSampling(_))
        ));
    }

    #[test]
    fn sample_keeps_only_top_k_candidates() {
        let mut rng = Rng::new(42);
        let sampling = Sampling {
            temperature: 1.0,
            top_k: 2,
            ..Sampling::default()
        };
        let row = [0.0, 5.0, 4.0, -10.0];
        for _ in 0..32 {
            assert!(matches!(sample(&row, &sampling, &mut rng), Ok(1 | 2)));
        }
    }

    #[test]
    fn pre_cancelled_generation_returns_cancelled() {
        let session = Scripted::new();
        let cancel = CancelToken::new();
        cancel.cancel();
        let error = generator()
            .generate(&session, "ab", 3, &cancel, &mut |_| true)
            .expect_err("must be cancelled");
        assert!(matches!(error, EngineError::Cancelled));
    }
}
